"""The assumptions registry — one place a pipeline stage declares what it assumes.

Every processing stage rests on assumptions about the data. When one quietly stops
holding, the stage does not fail; it returns a number that looks fine and is wrong.
That is how a dynamic-range metric spent months being reported as a measurement
uncertainty, and how a per-scan matrix could be discarded by the first pipeline step
without anything saying so.

The fix is not more documentation. Documentation and code drift apart — thz-core's own
wiki *already* listed "tail floor contaminated by signal content" as a known failure
mode of the very floor the uncertainty was built from, and nothing connected the two.
So an assumption is registered **once**, at the definition site of the check that
tests it, and that single registration is the source of both:

- the **runtime check**, run against real data and reported in the run log; and
- the **ledger document**, generated by :func:`render_assumptions_ledger`.

There is deliberately no second list to maintain. A new assumption is one
``@diagnostic`` decorator and nothing else.

Diagnostics never halt a run. They observe and report; what to do about a finding is
the analyst's call, and a run that stops halfway is less useful than a finished run
with an honest health report attached.
"""

from __future__ import annotations

import traceback
from dataclasses import dataclass, field
from enum import IntEnum
from typing import Callable, Iterable


class Severity(IntEnum):
    """How much a finding should worry you. Ordered, so they sort sensibly."""

    INFO = 0     # worth knowing; nothing is wrong
    WARN = 1     # an assumption is strained; results are usable but qualified
    FAIL = 2     # an assumption is broken; results that depend on it are not usable

    @property
    def label(self) -> str:
        return {Severity.INFO: "info", Severity.WARN: "warn", Severity.FAIL: "FAIL"}[self]


@dataclass(frozen=True)
class Problem:
    """What a check reports when it finds something.

    Deliberately carries no metadata about the diagnostic itself — the name, stage,
    severity, rationale and remedy all come from the registration, so a check cannot
    describe itself inconsistently with its own ledger entry.
    """

    message: str
    filename: str | None = None
    detail: dict = field(default_factory=dict)
    severity: Severity | None = None      # per-instance override, used sparingly


@dataclass(frozen=True)
class Finding:
    """A problem, joined to the registered metadata of the diagnostic that found it."""

    diagnostic: str
    stage: str
    severity: Severity
    message: str
    assumption: str
    remedy: str
    filename: str | None = None
    detail: dict = field(default_factory=dict)

    def format(self, *, indent: str = "") -> str:
        target = f" [{self.filename}]" if self.filename else ""
        return (f"{indent}{self.severity.label:>4}  {self.diagnostic}{target}\n"
                f"{indent}      {self.message}\n"
                f"{indent}      remedy: {self.remedy}")


@dataclass(frozen=True)
class Diagnostic:
    """One registered assumption and the check that tests it."""

    name: str
    stage: str
    assumption: str
    why: str
    remedy: str
    severity: Severity
    check: Callable[..., Iterable[Problem] | None]


DIAGNOSTIC_REGISTRY: dict[str, Diagnostic] = {}


def diagnostic(*, stage: str, assumption: str, why: str, remedy: str,
               severity: Severity = Severity.WARN, name: str | None = None):
    """Register a check, and with it the assumption it guards.

    Parameters
    ----------
    stage : str
        The pipeline stage whose assumption this is. Lets a run check only the stages
        it has actually executed.
    assumption : str
        The thing being assumed, stated plainly and positively — "the floor band has
        reached a noise plateau", not "check the floor band".
    why : str
        What goes wrong when it stops holding. This is the half that makes the ledger
        worth reading; write it for someone meeting the problem for the first time.
    remedy : str
        What to do about it. A finding without a remedy is just bad news.
    severity : Severity
        Default severity for this diagnostic's findings.

    The decorated function takes ``(dataset, config)`` and yields :class:`Problem`,
    or returns nothing when the assumption holds.
    """
    def register(function):
        entry = Diagnostic(
            name=name or function.__name__,
            stage=stage,
            assumption=assumption,
            why=why.strip(),
            remedy=remedy.strip(),
            severity=severity,
            check=function,
        )
        DIAGNOSTIC_REGISTRY[entry.name] = entry
        function.diagnostic = entry
        return function
    return register


def run_diagnostics(dataset, config: dict | None = None, *,
                    stage: str | None = None) -> list[Finding]:
    """Run every registered check (or just one stage's) and return the findings.

    A check that raises is itself reported as a FAIL rather than being allowed to take
    the run down — a broken diagnostic is a problem with the diagnostic, and losing an
    otherwise good analysis to it would be the worst of both worlds.
    """
    config = config or getattr(dataset, "config", None) or {}
    findings: list[Finding] = []

    for entry in DIAGNOSTIC_REGISTRY.values():
        if stage is not None and entry.stage != stage:
            continue
        try:
            problems = entry.check(dataset, config) or []
            for problem in problems:
                findings.append(Finding(
                    diagnostic=entry.name,
                    stage=entry.stage,
                    severity=problem.severity or entry.severity,
                    message=problem.message,
                    assumption=entry.assumption,
                    remedy=entry.remedy,
                    filename=problem.filename,
                    detail=problem.detail,
                ))
        except Exception as error:  # noqa: BLE001 — a broken check must not halt a run
            findings.append(Finding(
                diagnostic=entry.name,
                stage=entry.stage,
                severity=Severity.FAIL,
                message=f"the check itself raised {type(error).__name__}: {error}",
                assumption=entry.assumption,
                remedy="fix the diagnostic; this says nothing about your data",
                detail={"traceback": traceback.format_exc()},
            ))

    findings.sort(key=lambda finding: (-finding.severity, finding.stage, finding.diagnostic))
    return findings


def registered_stages() -> list[str]:
    """Every stage that has at least one registered assumption, in registration order."""
    seen: list[str] = []
    for entry in DIAGNOSTIC_REGISTRY.values():
        if entry.stage not in seen:
            seen.append(entry.stage)
    return seen


def render_assumptions_ledger() -> str:
    """Generate the ledger document from the registry.

    The document is *derived*, never edited. That is the whole point: an assumption
    documented in one place and checked in another is exactly the failure this module
    exists to prevent, so there is no hand-written copy that can fall out of step.
    """
    lines = [
        "# Assumptions ledger",
        "",
        "**Generated from `dataset_core.adapters.diagnostics`. Do not edit by hand** —",
        "edit the `@diagnostic` registration and regenerate, so the runtime check and",
        "this document can never disagree.",
        "",
        "Each entry is something a pipeline stage takes for granted. Every one of them",
        "is checked against real data at run time; none of them halts a run.",
        "",
    ]
    for stage in registered_stages():
        lines += [f"## Stage: `{stage}`", ""]
        for entry in DIAGNOSTIC_REGISTRY.values():
            if entry.stage != stage:
                continue
            lines += [
                f"### {entry.assumption}",
                "",
                f"- **Check:** `{entry.name}` (severity when broken: "
                f"**{entry.severity.label}**)",
                f"- **Why it matters:** {entry.why}",
                f"- **If it fails:** {entry.remedy}",
                "",
            ]
    return "\n".join(lines)
